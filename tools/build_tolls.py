# Builds tolls.js for the dashboard from research/tolls/*.json.
# Usage: python3 tools/build_tolls.py <path to research/tolls folder> <output tolls.js>
# Every number comes from the toll files written from NEXCO Drive Plaza; totals are summed here, never typed.
import json, glob, os, sys

src, out = sys.argv[1], sys.argv[2]
tolls, meta = {}, {}
for path in sorted(glob.glob(os.path.join(src, '*.json'))):
    d = json.load(open(path, encoding='utf-8'))
    key = d['key']
    legs, etc, cheap, cash = [], 0, 0, 0
    for l in d['legs']:
        rs = l['routes_listed_by_site']; r1 = rs[0]
        near = [r for r in rs if r['km'] <= r1['km'] * 1.15]       # ignore the site's long detours
        c = min(r['etc_toll'] for r in near)
        etc += r1['etc_toll']; cheap += c; cash += r1['regular_price']
        legs.append({'date': l['search_date_time'][:10], 'from': l['from'], 'to': l['to'], 'roads': l['roads_on_route_1'],
                     'etc': r1['etc_toll'], 'etcCheap': c, 'cash': r1['regular_price'], 'km': r1['km'], 'time': r1['time']})
    tolls[key] = {'legs': legs, 'etc': etc, 'etcCheap': cheap, 'cash': cash,
                  'notIncluded': d.get('not_included', []), 'problems': d.get('problems', '')}
    meta = {'source': d['calculator'], 'read': d['read_at'][:10], 'vehicle': d['vehicle_class'], 'method': d['leg_method']}
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_tolls.py from research/tolls/*.json. Estimates from NEXCO Drive Plaza; real tolls will differ.\n')
    f.write('window.TOLLS = ' + json.dumps(tolls, ensure_ascii=False, separators=(',', ':')) + ';\n')
    f.write('window.TOLLS_META = ' + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ';\n')
print({k: (v['etc'], v['etcCheap'], v['cash']) for k, v in tolls.items()})
