#!/usr/bin/env python3
"""Build flights.js from research/flights/FA.json and FB.json. Per-person price = Google's 2-adult total / 2, computed here.
Usage: python3 tools/build_flights.py research/flights flights.js"""
import json, sys, datetime
src, out = sys.argv[1:3]
FA = json.load(open(src + '/FA.json', encoding='utf-8'))
FB = json.load(open(src + '/FB.json', encoding='utf-8'))

def pp(total):  # whole dollars, half rounds up
    return int(total / 2 + 0.5)

def t12(iso):
    t = datetime.datetime.strptime(iso.rstrip('?')[:16], '%Y-%m-%dT%H:%M')
    return t.strftime('%-I:%M %p')

nonstop = []
for o in FA['options']:
    outs = [o['outbound']] + ([o['outbound_alt']] if o.get('outbound_alt') else [])
    nonstop.append({'airline': o['airline'],
        'out': [x['flight'] + ', ' + t12(x['jfk_depart']) + ' to ' + t12(x['hnd_arrive']) for x in outs],
        'back': [x['flight'] + ', ' + t12(x['hnd_depart']) + ' to ' + t12(x['jfk_arrive']) for x in o['returns']],
        'total': o['price_round_trip_2_adults_usd'], 'pp': pp(o['price_round_trip_2_adults_usd'])})

want = [('ANA', 'JFK-ITM via HND', '2027-02-26T13:05'), ('JAL', 'JFK-ITM via HND', '2027-02-26T12:30'),
        ('Cathay Pacific', 'JFK-KIX via HKG', '2027-02-26T01:45'), ('Korean Air', 'JFK-KIX via ICN', '2027-02-26T12:00')]
one = []
for a, r, dep in want:
    for o in FB['options']:
        if o['airline'] == a and o['route'] == r and o['jfk_depart'] == dep:
            if a == 'Cathay Pacific' and 'at HKG' in o['stops'] and o['price_round_trip_2_adults_usd'] != 2533: continue
            one.append({'airline': a, 'route': r.replace('JFK-', 'JFK to ').replace('ITM', 'Itami').replace('KIX', 'Kansai'),
                        'depart': t12(o['jfk_depart']), 'duration': o['duration'], 'stop': o['stops'].replace('1 stop, ', ''),
                        'total': o['price_round_trip_2_adults_usd'], 'pp': pp(o['price_round_trip_2_adults_usd'])}); break

by = {}
ns = [x['pp'] for x in nonstop]
by['A'] = {'lo': min(ns), 'hi': max(ns), 'what': 'nonstop to Tokyo Haneda, ANA or JAL'}
ito = [x['pp'] for x in one if 'Itami' in x['route']]
for k in ('B', 'C'):
    by[k] = {'lo': min(ito), 'hi': max(ito), 'what': 'one stop at Haneda, to Osaka Itami, ANA or JAL'}
meta = {'read': FA['read_at'][:10], 'source': 'Google Flights', 'nonstopSearch': FA['search'], 'oneStopSearch': FB['search'],
        'noNonstopOsaka': 'Google Flights shows no nonstop to Osaka from JFK, Newark or LaGuardia on Feb 26, 2027, and none from Osaka to JFK on Mar 13.',
        'typical': 'Google called the Tokyo round trip "typical", with similar trips usually $1,700 to $2,950 for two adults (so $850 to $1,475 each).'}
open(out, 'w', encoding='utf-8').write('// Generated by tools/build_flights.py from research/flights/*.json. Per-person = total for 2 adults / 2. Not a quote.\nwindow.FLIGHTS = ' +
    json.dumps({'nonstop': nonstop, 'oneStop': one, 'byRoute': by}, ensure_ascii=False) + ';\nwindow.FLIGHTS_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
print(json.dumps({'by': by, 'nonstop': [(x['airline'], x['pp']) for x in nonstop], 'one': [(x['airline'], x['route'], x['pp']) for x in one]}))
