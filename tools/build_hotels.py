# Builds hotels.js for the dashboard from the research files.
# Usage: python3 tools/build_hotels.py <path to research/hotels folder> <output hotels.js>
# Every number comes from the JSON files written during the hotels.com browser sessions; totals are summed here, never typed.
import json, os, re, sys
from urllib.parse import quote

src, out = sys.argv[1], sys.argv[2]

def load(key):
    return json.load(open(os.path.join(src, key + '.json'), encoding='utf-8'))

# Detail pages re-read live in the proof pass on 2026-11-12 (prices matched). The rest were read once.
REREAD = {'A0', 'A1', 'A2', 'A2b', 'A2c', 'A3', 'A4', 'A5', 'A6', 'B0', 'B1', 'B2', 'B3', 'B4'}
TIERS = ['lower', 'middle', 'higher']
PHOTOS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'hotel_photos.json'), encoding='utf-8'))
# Town used in the Google Maps search link (hotel name + town). A search link, not a pinned place.
TOWN = {'A0': 'Ota, Tokyo', 'A1': 'Hakone, Kanagawa', 'A2': 'Narai, Shiojiri, Nagano', 'A2b': 'Kiso, Nagano', 'A2c': 'Shiojiri, Nagano',
        'A3': 'Gifu / Nagano', 'A4': 'Takayama, Gifu', 'A5': 'Kanazawa, Ishikawa', 'A6': 'Kyoto', 'B0': 'Umeda, Osaka', 'B1': 'Himeji, Hyogo',
        'B2': 'Onomichi, Hiroshima', 'B3': 'Hiroshima', 'B4': 'Miyajima, Hatsukaichi, Hiroshima', 'B5': 'Kurashiki, Okayama', 'B6': 'Kobe, Hyogo',
        'C1': 'Nara', 'C2': 'Kyoto', 'C3': 'Kinosaki Onsen, Toyooka, Hyogo', 'C4': 'Himeji, Hyogo'}
A3_TOWN = {'Hotel Route-Inn Nakatsugawa Inter': 'Nakatsugawa, Gifu', 'TAOYA Kisoji': 'Nagiso, Nagano', 'Hotel Fukinomori': 'Nagiso, Nagano'}

def night(key):
    d = load(key)
    picks = []
    for p in d['picks']:
        hid = re.search(r'/(ho\d+)/', p['url']).group(1)
        ph = PHOTOS.get(hid)
        town = A3_TOWN.get(p['name']) or TOWN[d['key']]
        picks.append({
            'tier': p['tier'], 'name': p['name'],
            'maps': 'https://www.google.com/maps/search/?api=1&query=' + quote('%s, %s, Japan' % (p['name'], town)),
            'img': ('https://images.trvl-media.com/lodging/' + ph['p'] + '?impolicy=resizecrop&rw=598&ra=fit') if ph else '',
            'imgFront': bool(ph and ph['front']), 'imgShows': (ph or {}).get('shows', ''),
            'url': '%s?chkin=%s&chkout=%s&rm1=a2' % (p['url'], d['check_in'], d['check_out']),
            'stars': p['stars'], 'rating': p['guest_rating'], 'reviews': p['review_count'],
            'room': p['room_type'], 'nightly': p['price_per_night'], 'total': p['total_with_taxes'],
            'cancel': p['free_cancellation'], 'parking': p['parking'], 'member': bool(p.get('member_price')),
        })
    return {'key': d['key'], 'stop': d['stop'], 'checkIn': d['check_in'], 'checkOut': d['check_out'], 'nights': d['nights'],
            'qualifying': d['qualifying_count'], 'picks': picks, 'problems': d.get('problems', ''), 'reread': d['key'] in REREAD,
            'readAt': d['read_at'][:10]}

def total(keys, tier):
    s = 0
    for k in keys:
        d = load(k)
        by = {p['tier']: p for p in d['picks']}
        s += (by.get(tier) or d['picks'][0])['total_with_taxes']
    return round(s)

ROUTES = {
    # arrive = the Feb 27 night; nights = one key per calendar day Feb 28 .. Mar 5 (a 2-night stay repeats its key)
    'A': {'arrive': 'A0', 'nights': ['A1', 'A2', 'A3', 'A4', 'A5', 'A6'], 'alts': {'A2': ['A2b', 'A2c']},
          'variants': [('Sleeping in Narai-juku', ['A0', 'A1', 'A2', 'A3', 'A4', 'A5', 'A6']),
                       ('Narai night in Kiso-Fukushima', ['A0', 'A1', 'A2b', 'A3', 'A4', 'A5', 'A6']),
                       ('Narai night in Shiojiri', ['A0', 'A1', 'A2c', 'A3', 'A4', 'A5', 'A6'])]},
    'B': {'arrive': 'B0', 'nights': ['B1', 'B2', 'B3', 'B4', 'B5', 'B6'], 'alts': {},
          'variants': [('', ['B0', 'B1', 'B2', 'B3', 'B4', 'B5', 'B6'])]},
    'C': {'arrive': 'B0', 'nights': ['C1', 'C2', 'C2', 'C3', 'C3', 'C4'], 'alts': {},
          'variants': [('', ['B0', 'C1', 'C2', 'C3', 'C4'])]},
}

data = {}
for rid, r in ROUTES.items():
    keys = sorted(set([r['arrive']] + r['nights'] + [a for v in r['alts'].values() for a in v]))
    data[rid] = {
        'arrive': r['arrive'], 'nights': r['nights'], 'alts': r['alts'],
        'stays': {k: night(k) for k in keys},
        'totals': [{'label': label, 'lower': total(ks, 'lower'), 'middle': total(ks, 'middle'), 'higher': total(ks, 'higher')}
                   for label, ks in r['variants']],
    }
    for v in data[rid]['totals']:
        print(rid, v)

meta = {
    'source': 'hotels.com, read in a signed-in Chrome session with the exact dates, 2 adults, 1 room',
    'read': '2026-11-12', 'currency': 'USD',
    'rule': 'Class 3 to 4 stars, guest rating 8.0 or higher, 100 or more reviews (30 in small towns), parking where the car stays overnight.',
}
js = ('// Generated by tools/build_hotels.py from research/hotels/*.json. Prices as shown on hotels.com on the read date; they will change.\n'
      '// Nothing here is booked except the wedding hotel, which is not in this file.\n'
      'window.HOTELS = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
      'window.HOTELS_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
open(out, 'w', encoding='utf-8').write(js)
print('bytes', len(js))
