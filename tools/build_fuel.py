#!/usr/bin/env python3
"""Build fuel.js from research/fuel/fuel.json and routes.js distances. Usage: python3 tools/build_fuel.py research/fuel/fuel.json routes.js fuel.js"""
import json, re, subprocess, sys
src, routes, out = sys.argv[1:4]
d = json.load(open(src, encoding='utf-8'))
js = open(routes, encoding='utf-8').read()
tot = {}
for m in re.finditer(r'"id":"([ABC])".*?"totalKm":([\d.]+)', js, re.S):
    tot.setdefault(m.group(1), float(m.group(2)))
p = d['petrol']['yen_per_litre']; hi = d['economy_wltc_km_per_l']['high']['value']; lo = d['economy_wltc_km_per_l']['low']['value']
fuel = {}
for k, km in sorted(tot.items()):
    fuel[k] = {'km': round(km), 'litresLow': round(km / hi, 1), 'litresHigh': round(km / lo, 1),
               'yenLow': round(km / hi * p), 'yenHigh': round(km / lo * p)}
meta = {'petrol': p, 'petrolWhat': d['petrol']['what'], 'petrolSource': d['petrol']['source'], 'read': d['read_at'][:10],
        'econHigh': hi, 'econLow': lo, 'econSource': d['economy_wltc_km_per_l']['source'],
        'caveats': [d['petrol']['caveat'], d['economy_wltc_km_per_l']['caveat']]}
open(out, 'w', encoding='utf-8').write('// Generated by tools/build_fuel.py from research/fuel/fuel.json. Estimates, not quotes.\nwindow.FUEL = ' + json.dumps(fuel) + ';\nwindow.FUEL_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
print(fuel)
